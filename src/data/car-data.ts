export const getAllMakes = (): string[] =>
  Object.keys(CAR_DATA).sort((a, b) => a.localeCompare(b));

export const getModelsForMake = (make: string): string[] => {
  if (!make) return [];
  return CAR_DATA[make] ?? [];
};

export const generateYearOptions = (): string[] => {
  const currentYear = new Date().getFullYear();
  const minYear = currentYear - 40;
  const years: string[] = [];
  for (let y = currentYear; y >= minYear; y--) years.push(String(y));
  return years;
};
